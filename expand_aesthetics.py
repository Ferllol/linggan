# ---------------- merge ----------------
with open(PATH, encoding="utf-8") as f:
    data = json.load(f)

aes = data["aesthetics"]
errors = []
exp_keys = set()
for s in aes:
    sid = s["id"]
    if sid not in EXP:
        errors.append("缺少扩容数据: " + sid)
        continue
    exp_keys.add(sid)
    history, detail, color_sys, reps, apps, terms, radar = EXP[sid]
    # 保留现有 elements/materials
    s["history"] = history
    s["definition_detail"] = detail
    s["visual_features"] = {
        "color_system": color_sys,
        "elements": s["elements"],
        "materials": s["materials"],
    }
    s["representatives"] = reps
    s["applications"] = apps
    s["related_terms"] = terms
    s["radar_scores"] = radar

# 检查 EXP 是否多余
expra = set(EXP.keys())
if expra - exp_keys:
    errors.append("EXP 中有未使用 id: %s" % (expra - exp_keys))

# 校验
DIM = ["color_intensity", "tech", "nature", "darkness", "retro", "refinement"]
for s in aes:
    sid = s["id"]
    for fld in ["history", "definition_detail"]:
        if not s.get(fld, "").strip():
            errors.append("%s.%s 为空" % (sid, fld))
    vf = s.get("visual_features", {})
    if not vf.get("color_system", "").strip():
        errors.append("%s.visual_features.color_system 为空" % sid)
    for arr_name, mn in [("representatives", 2), ("applications", 2), ("related_terms", 2)]:
        arr = s.get(arr_name, [])
        if len(arr) < mn:
            errors.append("%s.%s 数量=%d（需≥%d）" % (sid, arr_name, len(arr), mn))
        for it in arr:
            if not str(it).strip():
                errors.append("%s.%s 有空项" % (sid, arr_name))
    rs = s.get("radar_scores", {})
    for d in DIM:
        if d not in rs:
            errors.append("%s.radar_scores 缺维度 %s" % (sid, d))
        else:
            v = rs[d]
            if not isinstance(v, int) or not (0 <= v <= 100):
                errors.append("%s.radar_scores.%s 非法值 %r" % (sid, d, v))

# 对称不变性：related 数量与结构未变（只新增字段，不动 related）
print("条目数:", len(aes))

if errors:
    print("== 校验失败 ==")
    for e in errors[:80]:
        print(e)
    raise SystemExit(1)


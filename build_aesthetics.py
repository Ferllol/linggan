seen = set()
dropped = []
for a, b, score, ra, rb in EDGES:
    assert a in id_set and b in id_set, "edge 引用不存在 id: %s-%s" % (a, b)
    key = tuple(sorted([a, b]))
    if key in DROP:
        dropped.append((a, b))
        continue
    if key in seen:
        dropped.append((a, b))
        continue
    seen.add(key)
    related[a].append({"id": b, "score": score, "reason": ra})
    related[b].append({"id": a, "score": score, "reason": rb})

# 对称性校验（结构上已保证，仍做最终检查）
errors = []
for a in ids:
    for rel in related[a]:
        b = rel["id"]
        # 找到 b 对 a 的关联
        mate = [r for r in related[b] if r["id"] == a]
        if not mate:
            errors.append("%s -> %s 缺少反向关联" % (a, b))
        elif mate[0]["score"] != rel["score"]:
            errors.append("%s <-> %s score 不一致: %d vs %d" % (a, b, rel["score"], mate[0]["score"]))

# 数量校验
for i in ids:
    n = len(related[i])
    if not (3 <= n <= 8):
        errors.append("%s related 数量=%d（需 3-8）" % (i, n))

